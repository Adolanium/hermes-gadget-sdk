#!/usr/bin/env python3
"""Generates core/src/font_cjk_data.cpp: a 12x12 bitmap CJK font.

Glyphs come from Fusion Pixel Font 12px monospaced (SIL OFL 1.1, (c) 2022 TakWolf), release
2026.10.25: the Taiwan-standard variant (zh_tw) for Traditional characters and the Simplified
variant (zh_hans) for characters that only exist in Simplified Chinese. The character set is Big5
(common and symbol blocks) plus GB2312 level 1, the CJK symbols and the fullwidth forms: about
7,000 glyphs, 18 bytes each (12 rows x 12 bits, MSB first).

  python3 tools/gen_cjk_font.py <dir with fusion-pixel-12px-monospaced-*.ttf>

Needs Pillow. The font files come from
https://github.com/TakWolf/fusion-pixel-font/releases/tag/2026.10.25
(fusion-pixel-font-12px-monospaced-ttf-v2026.10.25.zip). Its license is in LICENSES/Fusion-Pixel-OFL.txt.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
OUT = Path(__file__).resolve().parent.parent / "core" / "src" / "font_cjk_data.cpp"
SIZE = 12


def codepoints():
    """(traditional-capable set, simplified-only set) of code points."""
    big5, gb = set(), set()
    for codec, leads, trails, target in (
        ("big5", range(0xA1, 0xC7), list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)), big5),
        ("gb2312", range(0xA1, 0xD8), range(0xA1, 0xFF), gb),
    ):
        for lead in leads:
            for trail in trails:
                try:
                    ch = bytes([lead, trail]).decode(codec)
                except UnicodeDecodeError:
                    continue
                # Only U+2E80 and up: general punctuation (curly quotes, dashes) stays
                # one column wide and folds to ASCII like the other Latin text.
                if len(ch) == 1 and ord(ch) >= 0x2E80:
                    target.add(ord(ch))
    common = set(range(0x3000, 0x3040)) | set(range(0xFF01, 0xFF5F))  # CJK symbols, fullwidth forms
    return big5 | common, gb - big5 - common


def render(font, cp):
    im = Image.new("1", (SIZE, SIZE), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), chr(cp), font=font, fill=1)
    if not im.getbbox():
        return None
    bits = [1 if im.getpixel((x, y)) else 0 for y in range(SIZE) for x in range(SIZE)]
    return bytes(int("".join(map(str, bits[i:i + 8])).ljust(8, "0"), 2) for i in range(0, SIZE * SIZE, 8))


def main():
    tw = ImageFont.truetype(str(FONT_DIR / "fusion-pixel-12px-monospaced-zh_tw.ttf"), SIZE)
    hans = ImageFont.truetype(str(FONT_DIR / "fusion-pixel-12px-monospaced-zh_hans.ttf"), SIZE)
    trad, simp = codepoints()
    entries = []
    for cps, font in ((trad, tw), (simp, hans)):
        for cp in cps:
            data = render(font, cp)
            if data:
                entries.append((cp, data))
    entries.sort()
    lines = [
        "// Generated by tools/gen_cjk_font.py from Fusion Pixel Font 12px monospaced 2026.10.25",
        "// (SIL OFL 1.1, (c) 2022 TakWolf; see LICENSES/Fusion-Pixel-OFL.txt).",
        "// 12x12 glyphs, 18 bytes each (row-major, MSB first), sorted by code point.",
        '#include "hg/font.hpp"',
        "",
        "#if HG_CJK_FONT",
        "",
        '#include "hg/font_cjk.hpp"',
        "",
        "namespace hg::font {",
        "",
        f"const int kCjkGlyphCount = {len(entries)};",
        "",
        "const uint32_t kCjkCodepoints[] = {",
    ]
    cps = [f"0x{cp:04X}" for cp, _ in entries]
    for i in range(0, len(cps), 12):
        lines.append("    " + ", ".join(cps[i:i + 12]) + ",")
    lines += ["};", "", "const uint8_t kCjkBitmaps[] = {"]
    for _, data in entries:
        lines.append("    " + ",".join(f"0x{b:02X}" for b in data) + ",")
    lines += ["};", "", "}  // namespace hg::font", "", "#endif  // HG_CJK_FONT", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(len(entries), "glyphs ->", OUT)


main()
