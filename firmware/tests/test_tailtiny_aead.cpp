// The same nonce tail as wireguard-lwip's little-endian counter, and as Tailscale's big-endian one.
const uint64_t kRfcNonceLittle = 0x0807060504030201ULL;
const uint64_t kRfcNonceBig = 0x0102030405060708ULL;

std::vector<uint8_t> sealed() {
  std::vector<uint8_t> v(kRfcCiphertext, kRfcCiphertext + sizeof kRfcCiphertext);
  v.insert(v.end(), kRfcTag, kRfcTag + sizeof kRfcTag);
  return v;
}

