// Builds the Hermes dashboard's Gadgets tab: plugin/dashboard/src/index.jsx -> plugin/dashboard/dist/index.js.
//
//   npm run build:dashboard-tab           write dist/index.js
//   node scripts/dashboard-tab.mjs --check   exit 1 when dist/index.js differs from a fresh build
//
// React is not bundled: the source reads it from the dashboard's plugin SDK
// (window.__HERMES_PLUGIN_SDK__), and JSX compiles to React.createElement on that object.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../../plugin/dashboard/", import.meta.url));
export const SOURCE = `${root}src/index.jsx`;
export const OUTPUT = `${root}dist/index.js`;

const BANNER = "// Generated by site/scripts/dashboard-tab.mjs from plugin/dashboard/src/index.jsx. Do not edit;\n"
  + "// change the source and run `npm run build:dashboard-tab` in site/.";

export async function bundle() {
  const result = await build({
    entryPoints: [SOURCE],
    bundle: true,
    write: false,
    format: "iife",
    target: "es2020",
    charset: "utf8",
    jsx: "transform",
    jsxFactory: "React.createElement",
    jsxFragment: "React.Fragment",
    legalComments: "none",
    banner: { js: BANNER },
    logLevel: "silent",
    absWorkingDir: fileURLToPath(new URL("..", import.meta.url)),
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fresh = await bundle();
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== fresh) {
      console.error("plugin/dashboard/dist/index.js is out of date: run `npm run build:dashboard-tab` in site/");
      process.exit(1);
    }
  } else {
    await writeFile(OUTPUT, fresh);
    console.log(`wrote ${OUTPUT}`);
  }
}
